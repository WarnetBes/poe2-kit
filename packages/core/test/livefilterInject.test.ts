/** Разогнать known-сеты выше порогов включения проверки, сохранив данные opts. */
function bigOpts(opts: SelfCheckOptions): SelfCheckOptions {
  const classes = new Set(opts.classes);
  for (let i = 0; i < 12; i++) classes.add(`class${i}`);
  const bases = new Map(opts.bases);
  for (let i = 0; i < 505; i++) bases.set(`base${i}`, `Base${i}`);
  return { classes, bases, loose: opts.loose };
}
