const NS_BASE = [
  '# NeverSlink-style base',
  '# credits here',
  '#===',
  '# [[0100]] OVERRIDE AREA 1 - Override ALL rules here',
  '#===',
  '',
  '#===',
  '# [[0200]] Currency',
  '#===',
  'Show',
  '    BaseType == "Orb of Transmutation"',
  '    SetFontSize 45',
  '',
].join('\n');

/** Динамический блок в формате генератора (баннеры + маркеры). */
function dynBlock(): string {
  return [
    '#==============================================================================',
    '# [[DYNAMIC LOOT FILTER]] — generated by poe2-kit livefilter',
    '#==============================================================================',
    '# divine spotlight',
    'Show',
    '    BaseType == "Divine Orb"',
    '    SetFontSize 45',
    '',
    '#==============================================================================',
    '# [[END DYNAMIC LOOT FILTER]]',
    '#==============================================================================',
  ].join('\n');
}

describe('injectBlock (порт injector.go:69-81)', () => {
  it('блок встаёт ПЕРЕД первой секцией NS, после шапки/кредитов', () => {
    const out = injectBlock(NS_BASE, dynBlock());
    const blockAt = out.indexOf(DYNAMIC_BLOCK_START);
    const firstSection = out.indexOf('# [[0200]]');
    const credits = out.indexOf('# credits here');
    expect(blockAt).toBeGreaterThan(-1);
    expect(blockAt).toBeGreaterThan(credits);
    expect(blockAt).toBeLessThan(firstSection);
    // OVERRIDE-секция тоже реальная секция (#===\n# [[0100]]): блок обязан быть ДО неё too?
    // НЕ обязательна: грабля §9.4 — точка = первая framed-секция; здесь это 0100.
    expect(blockAt).toBeLessThan(out.indexOf('# [[0100]]'));
  });

  it('повторная инжекция не накапливает блоки (reOldBlock, injector.go:56-60)', () => {
    const once = injectBlock(NS_BASE, dynBlock());
    const twice = injectBlock(once, dynBlock());
    expect(twice.match(new RegExp(DYNAMIC_BLOCK_START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g'))!.length).toBe(1);
    expect(stripOldDynamicBlocks(twice)).toBe(NS_BASE); // вырезание = исходная база (бесследный откат)
  });

  it('блок с «$» не ломается: склейка конкатенацией, не regex-replace (injector.go:76-78)', () => {
    const block = dynBlock().replace('divine spotlight', 'divine $type-$1 spotlight');
    const out = injectBlock(NS_BASE, block);
    expect(out).toContain('divine $type-$1 spotlight');
  });

  it('чужой фильтр без NS-секций: блок наверх', () => {
    const out = injectBlock('Show\n    BaseType == "Foo"\n', dynBlock());
    expect(out.indexOf(DYNAMIC_BLOCK_START)).toBeLessThan(out.indexOf('Show'));
  });
});

describe('writeFilterAtomic', () => {
  it('temp+rename: контент записан, tmp-файлов не осталось', () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'p3-'));
    const dest = path.join(dir, 't.filter');
    writeFilterAtomic(dest, 'Show\n');
    expect(fs.readFileSync(dest, 'utf8')).toBe('Show\n');
    const leftovers = fs.readdirSync(dir).filter((f) => f.includes('.tmp-'));
    expect(leftovers).toHaveLength(0);
    fs.rmSync(dir, { recursive: true, force: true });
  });
});

describe('selfCheckBlock (порт selfcheck.go:47-147)', () => {
  const opts = (): SelfCheckOptions => ({
    classes: new Set(['amulets', 'rings']),
    bases: new Map([
      ['divine orb', 'Divine Orb'],
      ['amulet', 'Amulet'],
    ]),
    loose: ['eng', 'cataly'],
  });
  // пороги для включения проверки: набор меньше порогов → проверка выключена,
  // поэтому в тестах ниже сознательно проверяем «малые» кейсы на общем
  // блоке с/bases>=порогами не требуется — логика чистая, пороги тестируем отдельно.

  it('unknown Class → правило выброшено ЦЕЛИКОМ, файл валиден (selfcheck.go:44-46)', () => {
    const block = [
      '# hdr',
      'Show',
      '    Class == "Vkusny Class"',
      '    SetFontSize 45',
      '',
      'Show',
      '    Class == "Amulets"',
      '',
    ].join('\n');
    const big = bigOpts(opts());
    const res = selfCheckBlock(block, big);
    expect(res.dropped).toBe(1);
    expect(res.block).toContain('Class == "Amulets"');
    expect(res.block).not.toContain('Vkusny');
    expect(res.unknown).toContain('Class Vkusny Class');
  });

  it('mixed list: unknown-значение вырезано, известные остались (строка пересобрана)', () => {
    const block = 'Show\n    BaseType == "Divine Orb" "Catalyst"\n\n';
    const res = selfCheckBlock(block, bigOpts(opts()));
    expect(res.block!.replace(/\n+$/, '')).toBe('Show\n    BaseType == "Divine Orb"');
    expect(res.unknown).toEqual(['BaseType Catalyst']);
  });

  it('loose-значение: подстрока известного проходит; unknown loose — нет', () => {
    const block = 'Show\n    BaseType "Catalyst Killer"\n    BaseType "Eng"\n\n'.replace('BaseType "Eng"', 'BaseType "zzz"');
    const res = selfCheckBlock(block, bigOpts(opts()));
    expect(res.unknown).toContain('BaseType zzz');
    expect(res.block).not.toContain('zzz');
  });

  it('опустевший отрицательный список (!=) — условие вон, правило живёт (selfcheck.go:127-128)', () => {
    const block = 'Hide\n    BaseType != "Catalyst"\n    Rarity == "Rare"\n\n';
    const res = selfCheckBlock(block, bigOpts(opts()));
    expect(res.dropped).toBe(0);
    expect(res.block!.replace(/\n+$/, '')).toBe('Hide\n    Rarity == "Rare"');
  });

  it('порог качества знаний не достигнут → block null, проверка выключена (selfcheck.go:20-23)', () => {
    expect(SELFCHECK_MIN_CLASSES).toBe(10);
    expect(SELFCHECK_MIN_BASES).toBe(500);
    const res = selfCheckBlock('Show\n    BaseType == "Catalyst"\n', opts()); // 2 класса, 2 базы
    expect(res.block).toBeNull();
    expect(res.dropped).toBe(0);
  });

  it('knownSetsFromBaseFilter: uncomment-строги и loose-значения собираются (neversink.go:87-104)', () => {
    const ns = [
      '#Hide',                              // закомментированное правило…
      '#    BaseType == "Hidden Base"',     // …базы strict-фильтров живут в комментариях
      '#',
      'Show',
      '    Class == "Body Armours"',
      '    BaseType "Foo"',                 // loose без оператора
      '    BaseType == "Real Base"',
    ].join('\n');
    const sets = knownSetsFromBaseFilter(ns);
    expect(sets.bases.get('hidden base')).toBe('Hidden Base');
    expect(sets.bases.get('real base')).toBe('Real Base'); // после loose «foo» оригинал не потерян
    expect(sets.classes.has('body armours')).toBe(true);
    expect(sets.loose).toContain('foo');
    expect(sets.classCount).toBe(1);
    expect(sets.baseCount).toBe(2);
  });
});

describe('composeLiveFilter (clean end-to-end, без диска)', () => {
  const snap: LiveFilterSnapshot = {
    schemaVersion: LIVE_FILTER_SCHEMA_VERSION,
    league: 'test',
    generatedAt: '2026-10-12T00:00:00Z',
    rates: { divineEx: 500, chaosEx: 0.5 },
    currency: [
      { name: 'Divine Orb', category: 'currency', valueEx: 500 },
      { name: 'Catalyst', category: 'currency', valueEx: 999 }, // unknown базе — вырезана SelfCheck'ом
    ],
    uniqueBases: {},
    exceptional: [],
    sources: {},
  };

  // База выше порогов SelfCheck: >=10 классов, >=500 точных баз (+ реалистично:
  // strict-NS держит базы в комментариях). Divine Orb и Catalyst — со значением:
  // Divine базе известен, Catalyst — НЕТ.
  const filler: string[] = ['Show', '    BaseType == "Divine Orb"', ''];
  for (let i = 0; i < 12; i++) filler.push('Show', `    Class == "Klass ${i}"`, '');
  for (let i = 0; i < 505; i++) filler.push(i % 2 ? '#Show' : 'Show', `    BaseType == "Filler Base ${i}"`, '');
  const bigBase = [NS_BASE, ...filler].join('\n');

  it('full pipeline: unknown отрезан, известные живы, инжект перед секциями, откат побайтов', () => {
    const composed = composeLiveFilter(bigBase, snap, { thresholdEx: 10, hideLowRarityGear: false });
    expect(composed.content).toContain(DYNAMIC_BLOCK_START);
    // Divine Orb известен базе → divine-spotlight жив; Catalyst unknown базе —
    // отрезан генераторной канонизацией (первая линия) с честным ворнингом
    expect(composed.dynamicBlock).toContain('"Divine Orb"');
    expect(composed.dynamicBlock).not.toContain('Catalyst');
    expect(composed.stats.warnings.join('\n')).toContain('Catalyst');
    // SelfCheck (вторая линия) ничего легитимного не тронул
    expect(composed.selfCheck!.unknown.filter((u) => u.includes('Divine Orb'))).toHaveLength(0);
    // откат побайтов: strip → исходная база
    expect(stripOldDynamicBlocks(composed.content)).toBe(bigBase);
  });

  it('малая база: SelfCheck выключен порогом (selfCheck === null)', () => {
    const small = composeLiveFilter(NS_BASE, snap, { thresholdEx: 10, hideLowRarityGear: false });
    expect(small.selfCheck).toBeNull();
    // канонизация генератора работает и тут (не зависит от порогов SelfCheck)
    expect(small.stats.warnings.join('\n')).toContain('Catalyst');
  });
});

